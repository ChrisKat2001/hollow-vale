function drawSprite(canvas, name, opts = {}) {
  const sp = SPRITES[name]; if (!canvas || !sp) return;
  const n = 16, scale = Math.floor(canvas.width / n);
  const ctx = canvas.getContext("2d");
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  sp.px.forEach((row, j) => [...row.padEnd(n, ".")].slice(0, n).forEach((ch, i) => {
    if (ch === ".") return;
    ctx.fillStyle = opts.grey ? "#4a4048" : (sp.pal[ch] || "#000");
    ctx.fillRect(i * scale, j * scale, scale, scale);
  }));
}
